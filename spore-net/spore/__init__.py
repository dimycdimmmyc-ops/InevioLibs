"""
SPORE — живая сеть одним модулем.
Встраивающий даёт почву — модуль живёт.

Версия: 1.2.0
"""

__version__ = '1.2.0'
__author__ = 'SPORE'

from .core.life import цикл_дыхания, условие_зимовки
from .core.chain import зачать
from .spores.discovery import найти_соседей, выпустить_спору
from .hyphae.grow import создать_гифу, принять_сок
from .fruits.deliver import доставить
from .winter.core import зимовать, пробудиться, загрузить_ядро

import json
import time


class SporeNode:
    """
    Один узел живой сети.
    Публичное API: дышать, отправить, принять, найти_соседей,
    зимовать, пробудиться, статус, выбрать_почву.
    """

    def __init__(self, почва, имя='узел', направление='V'):
        self.почва = почва
        self.имя = имя
        self.направление = направление

        грибница = пробудиться(почва, имя)
        if грибница is None:
            грибница = self._новая_грибница(имя, направление, почва)

        self.грибница = грибница

    def дышать(self):
        """Один цикл дыхания. Возвращает новый сигнал или None."""
        сигнал = self._получить_сигнал()
        if сигнал is None:
            if условие_зимовки(self.грибница):
                self.зимовать()
            return None

        результат = цикл_дыхания(self.грибница, сигнал, self.почва)
        if результат['цикл'] == 'завершён':
            return результат['новый_сигнал']
        return None

    def отправить(self, кому, данные):
        """Доставить данные соседу."""
        return доставить(self.грибница, self.почва, кому, данные)

    def принять(self, ждать_сек=0.0):
        """Принять сок из почвы (с опциональным ожиданием)."""
        if ждать_сек <= 0:
            return принять_сок(self.почва)
        дедлайн = time.time() + ждать_сек
        while time.time() < дедлайн:
            сок = принять_сок(self.почва)
            if сок:
                return сок
            time.sleep(0.05)
        return None

    def найти_соседей(self):
        """Discovery — кто рядом резонирует."""
        return найти_соседей(self.почва, self.направление)

    def зимовать(self):
        """Свернуть в ядро."""
        return зимовать(self.грибница)

    def пробудиться(self):
        """Развернуть из ядра."""
        новая = пробудиться(self.почва, self.имя)
        if новая:
            self.грибница = новая
            return True
        return False

    def статус(self):
        """Краткая сводка состояния."""
        return {
            'имя': self.грибница.get('имя'),
            'почва': self.почва.тип(),
            'пористость': self.почва.пористость(),
            'питательность': self.почва.питательность(),
            'гиф': len(self.грибница.get('гифы', [])),
            'плодов': len(self.грибница.get('плоды', [])),
            'память': len(self.грибница.get('память', [])),
            'соседей': len(self.почва.соседи()),
            'глубина': self.грибница.get('глубина', 0)
        }

    @staticmethod
    def выбрать_почву(почвы):
        """
        Авторский выбор почвы:
        максимальное произведение пористости и питательности.
        """
        if not почвы:
            return None
        лучшая = None
        лучший_счёт = -1
        for п in почвы:
            счёт = п.пористость() * п.питательность()
            if счёт > лучший_счёт:
                лучший_счёт = счёт
                лучшая = п
        return лучшая

    def _новая_грибница(self, имя, направление, почва):
        return {
            'имя': имя,
            'почва': почва.тип(),
            'пористость_почвы': почва.пористость(),
            'питательность_почвы': почва.питательность(),
            'форма': 'встраивание' if почва.пористость() > 0.5 else 'поверх',
            'исходное_направление': направление,
            'споры': [],
            'гифы': [],
            'узлы': [],
            'швы': [],
            'плоды': [],
            'память': ['рождение:' + имя],
            'связи': [],
            'глубина': 0,
            'phi': {'нейтрал': 'радость', 'страх': 'интерес'},
            'выгоды': ['дать'],
            'выгоды_партнёра': ['взять'],
            'изменения': ['маршрут_1', 'маршрут_2'],
            'f1': {'маршрут_1': 1.0, 'маршрут_2': 2.0},
            'f2': {'маршрут_1': 2.0, 'маршрут_2': 1.0},
            'реакции': ['принять', 'ответить', 'запомнить'],
            'возмущения': ['потеря_связи', 'помеха']
        }

    def _получить_сигнал(self):
        ответ = self.почва.получить()
        if ответ is None:
            return None
        от_кого, данные = ответ
        try:
            пакет = json.loads(данные)
        except Exception:
            return None

        if пакет.get('тип') == 'спора':
            return {
                'v': 1, 'a': 1, 'k': 1,
                'стимул': 'спора',
                'эмоция': 'нейтрал',
                'от': от_кого
            }
        if пакет.get('тип') == 'сок':
            return {
                'v': 1, 'a': 1, 'k': 1,
                'стимул': 'сок',
                'эмоция': 'нейтрал',
                'от': от_кого,
                'данные': пакет.get('данные')
            }
        return None