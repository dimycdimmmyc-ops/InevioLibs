"""Споры: поиск соседей через резонанс."""
import json


СИГНАЛ_ПОИСКА = 'SPORE_DISCOVER'


def выпустить_спору(направление='V', сила=1.0, пористость=0.5):
    return {
        'тип': 'спора',
        'направление': направление,
        'сила': сила,
        'пористость': пористость
    }


def резонанс(сок_а, сок_б):
    if сок_а['направление'] == сок_б['направление']:
        return 0.0
    разница = abs(сок_а['сила'] - сок_б['сила'])
    if разница > 0.5:
        return 0.0
    return 1.0 - разница


def найти_соседей(почва, своё_направление='V'):
    """
    Рассылаем спору всем известным соседям,
    потом слушаем ответы.
    """
    спора = выпустить_спору(
        направление=своё_направление,
        сила=1.0,
        пористость=почва.пористость()
    )
    пакет = json.dumps(спора).encode('utf-8')

    резонирующие = []
    for сосед in почва.соседи():
        почва.отправить(сосед, пакет)

    # Слушаем ответы
    for _ in range(50):
        ответ = почва.получить()
        if ответ is None:
            break
        от_кого, данные = ответ
        try:
            чужой = json.loads(данные)
            if чужой.get('тип') == 'спора':
                р = резонанс(спора, чужой)
                if р > 0:
                    резонирующие.append((от_кого, чужой, р))
        except Exception:
            pass

    return резонирующие
