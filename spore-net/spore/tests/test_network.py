"""
Сетевой тест: два SporeNode общаются через UDP на localhost.
"""
import sys, time
sys.path.insert(0, "E:/spore_pkg")

from spore import SporeNode
from spore.soil.socket import ПочваSocket
from spore.soil.socket import ПочваSocket


ПОРТ_А = 5010
ПОРТ_Б = 5011


def поднять_узел(имя, порт, направление):
    почва = ПочваSocket('127.0.0.1', порт)
    узел = SporeNode(почва, имя=имя, направление=направление)
    return узел


def main():
    узел_а = поднять_узел('Аня', ПОРТ_А, 'V')
    узел_б = поднять_узел('Борис', ПОРТ_Б, 'A')

    print("Статус А:", узел_а.статус())
    print("Статус Б:", узел_б.статус())

    print("\n--- Аня шлёт спору Борису ---")
    узел_а.почва.отправить(('127.0.0.1', ПОРТ_Б),
                           '{"тип":"спора","направление":"V","сила":1.0,"пористость":0.5}')

    time.sleep(0.1)
    ответ = узел_б.почва.получить()
    print("Борис получил:", ответ)

    print("\n--- Борис отвечает Ане ---")
    узел_б.почва.отправить(('127.0.0.1', ПОРТ_А),
                           '{"тип":"спора","направление":"A","сила":1.0,"пористость":0.5}')

    time.sleep(0.1)
    ответ_а = узел_а.почва.получить()
    print("Аня получила:", ответ_а)

    print("\n--- Аня шлёт сообщение через доставить() ---")
    ок = узел_а.отправить(('127.0.0.1', ПОРТ_Б), {'текст': 'Привет, Борис!'})
    print("Отправка:", ок)

    time.sleep(0.1)
    принято = узел_б.принять()
    print("Борис принял:", принято)

    print("\n--- Финальный статус ---")
    print("Аня:", узел_а.статус())
    print("Борис:", узел_б.статус())

    print("\n--- Зимовка Ани ---")
    ядро = узел_а.зимовать()
    print("Ядро сохранено:", ядро['имя'], "| память:", len(ядро['память']))

    print("\n--- Пробуждение Ани ---")
    узел_а2 = поднять_узел('Аня', ПОРТ_А + 2, 'V')
    print("Аня 2:", узел_а2.статус())
    print("Память из ядра:", узел_а2.грибница['память'][:3])


if __name__ == '__main__':
    main()
