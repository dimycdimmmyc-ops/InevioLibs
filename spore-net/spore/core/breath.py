"""Дыхание: вдох — прямой проход, выдох — обратный."""
from .chain import (зачать, притяжение, доверие, память,
                    переосмысление, сговор, сдвиг, отбор, замыкание)


def _спора_в_звено(спора):
    """
    Превращает спору в звено конвейера,
    чтобы притяжение могло с ней работать.
    """
    if спора is None:
        return None
    if 'тело' in спора and 'leading' in спора.get('тело', {}):
        return спора  # уже звено

    направление = спора.get('направление', 'V')
    # Синтетический сигнал из споры
    сигнал = {
        'v': 1 if направление == 'V' else 0,
        'a': 1 if направление == 'A' else 0,
        'k': 1 if направление == 'K' else 0,
    }
    return зачать(сигнал)


def _найти_дополнение(грибница):
    for с in грибница.get('споры', []):
        if с.get('состояние') == 'покой':
            return _спора_в_звено(с)
    return None


def _найти_общую_точку(грибница):
    память_ = грибница.get('память', [])
    if not память_:
        return None
    return память_[0]


def вдох(грибница, сигнал, среда):
    з0 = зачать(сигнал)
    if з0 is None:
        return None
    цепь = [з0]

    дополнение = _найти_дополнение(грибница)
    з1 = притяжение(з0, дополнение)
    if з1 is None:
        return {'цепь': цепь, 'итог': 'одиночество'}
    цепь.append(з1)

    з2 = доверие(з1, _найти_общую_точку(грибница))
    if з2['имя'] == 'недоверие':
        return {'цепь': цепь + [з2], 'итог': 'разрыв'}
    цепь.append(з2)

    з3 = память(з2, сигнал.get('стимул', 'общее'),
                сигнал.get('эмоция', 'нейтрал'))
    цепь.append(з3)

    з4 = переосмысление(з3, грибница.get('phi', {}))
    цепь.append(з4)

    з5 = сговор(з3, з4,
                грибница.get('выгоды', []),
                грибница.get('выгоды_партнёра', []))
    цепь.append(з5)

    з6 = сдвиг(з5, грибница.get('сдвиг_k', 0))
    цепь.append(з6)

    з7 = отбор(з6,
               грибница.get('изменения', []),
               грибница.get('f1', {}),
               грибница.get('f2', {}))
    цепь.append(з7)

    з8 = замыкание(з7,
                   грибница.get('реакции', []),
                   грибница.get('возмущения', []))
    цепь.append(з8)

    for i in range(len(цепь) - 1):
        цепь[i]['след'] = цепь[i+1]

    return {'цепь': цепь, 'итог': 'замкнута'}


def выдох(грибница, плод, среда):
    if not плод['тело'].get('выживет', True):
        return {'итог': 'плод_погиб'}

    новый_сигнал = {
        'v': плод['тело'].get('реакций', 1),
        'a': плод['тело'].get('возмущений', 1),
        'k': len(плод['тело'].get('выжившие', [])),
        'имя': f"плод:{грибница.get('имя', '?')}"
    }

    return {'итог': 'выдохнут', 'новый_сигнал': новый_сигнал}
