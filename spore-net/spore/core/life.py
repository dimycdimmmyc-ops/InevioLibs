"""Жизненный цикл: дыхание + условие зимовки."""
from .breath import вдох, выдох


def цикл_дыхания(грибница, сигнал, среда):
    результат_вдоха = вдох(грибница, сигнал, среда)
    if результат_вдоха is None or результат_вдоха['итог'] != 'замкнута':
        причина = результат_вдоха['итог'] if результат_вдоха else 'мёртвый_сигнал'
        return {'цикл': 'прерван', 'причина': причина}

    плод = результат_вдоха['цепь'][-1]
    результат_выдоха = выдох(грибница, плод, среда)

    if результат_выдоха['итог'] != 'выдохнут':
        return {'цикл': 'прерван_на_выдохе'}

    память_ = грибница.get('память', [])
    грибница['память'] = память_ + [плод]

    return {'цикл': 'завершён',
            'новый_сигнал': результат_выдоха['новый_сигнал']}


def условие_зимовки(грибница):
    пористость = грибница.get('пористость_почвы', 1.0)
    живые = [г for г in грибница.get('гифы', []) if г.get('сила', 0) > 0.1]
    if пористость > 0.05:
        return False
    if живые:
        return False
    return True
