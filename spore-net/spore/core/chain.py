"""Конвейер: 9 звеньев от зачатия до замыкания."""


def _append(lst, x):
    n = len(lst)
    new_lst = [None] * (n + 1)
    for i in range(n):
        new_lst[i] = lst[i]
    new_lst[n] = x
    return new_lst


def зачать(сигнал):
    total = сигнал.get('v', 0) + сигнал.get('a', 0) + сигнал.get('k', 0)
    if total == 0:
        return None
    vec = (сигнал['v']/total, сигнал['a']/total, сигнал['k']/total)
    labels = ['V', 'A', 'K']
    best = 0
    for i in range(1, 3):
        if vec[i] > vec[best]:
            best = i
    return {
        'звено': 0,
        'имя': 'зачатие',
        'тело': {'vec': vec, 'leading': labels[best]},
        'печать': ('зачатие', labels[best], 0)
    }


def притяжение(з_а, з_б):
    if з_б is None:
        return None
    м_а = з_а['тело']['leading']
    м_б = з_б['тело']['leading']
    if м_а == м_б:
        return None
    return {
        'звено': 1,
        'имя': 'притяжение',
        'тело': {'пара': (м_а, м_б), 'сила': 1.0},
        'печать': ('притяжение', м_а + м_б, 1)
    }


def доверие(з_притяжения, общая_точка):
    if общая_точка is None:
        return {'звено': 2, 'имя': 'недоверие',
                'тело': {'вердикт': 'отказ'},
                'печать': ('недоверие', 0, 2)}
    return {'звено': 2, 'имя': 'доверие',
            'тело': {'вердикт': 'принято', 'точка': общая_точка},
            'печать': ('доверие', общая_точка, 2)}


def память(з_доверия, стимул, эмоция):
    return {'звено': 3, 'имя': 'память',
            'тело': {'стимул': стимул, 'эмоция': эмоция},
            'печать': ('память', (стимул, эмоция), 3)}


def переосмысление(з_памяти, phi):
    старый = з_памяти['тело']['эмоция']
    новый = phi.get(старый, старый)
    return {'звено': 4, 'имя': 'переосмысление',
            'тело': {'было': старый, 'стало': новый},
            'печать': ('переосмысление', (старый, новый), 4)}


def сговор(з_а, з_б, выгоды_а, выгоды_б):
    if not выгоды_а or not выгоды_б:
        return {'звено': 5, 'имя': 'сговор',
                'тело': {'точка': ('дефолт', 'дефолт')},
                'печать': ('сговор', ('дефолт', 'дефолт'), 5)}
    точка = (выгоды_а[0], выгоды_б[0])
    return {'звено': 5, 'имя': 'сговор',
            'тело': {'точка': точка},
            'печать': ('сговор', точка, 5)}


def сдвиг(з_сговора, k):
    return {'звено': 6, 'имя': 'сдвиг',
            'тело': {'k': k, 'ось': 'переставлена'},
            'печать': ('сдвиг', k, 6)}


def отбор(з_сдвига, изменения, f1, f2):
    выжившие = []
    for x in изменения:
        доминируем = False
        for y in изменения:
            if x == y:
                continue
            if f1.get(y, 0) >= f1.get(x, 0) and f2.get(y, 0) >= f2.get(x, 0):
                if f1.get(y, 0) > f1.get(x, 0) or f2.get(y, 0) > f2.get(x, 0):
                    доминируем = True
                    break
        if not доминируем:
            выжившие = _append(выжившие, x)
    return {'звено': 7, 'имя': 'отбор',
            'тело': {'выжившие': выжившие},
            'печать': ('отбор', tuple(выжившие), 7)}


def замыкание(з_отбора, реакции, возмущения):
    выживет = len(реакции) >= len(возмущения)
    return {'звено': 8, 'имя': 'замыкание',
            'тело': {'выживет': выживет,
                     'реакций': len(реакции),
                     'возмущений': len(возмущения)},
            'печать': ('замыкание', выживет, 8)}
