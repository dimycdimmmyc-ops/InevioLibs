"""Плоды: доставка сообщений через гифы."""
import json


def вырастить_плод(узел, данные):
    return {
        'тип': 'плод',
        'узел': узел.get('метка', 'неизвестный'),
        'плотность': узел.get('плотность', 0),
        'данные': данные,
        'память': узел.get('память', [])[-20:]
    }


def доставить(грибница, почва, кому, данные):
    """
    1. Ищем существующую гифу к цели.
    2. Если адрес известен — растим гифу напрямую.
    3. Если нет — ищем соседей через споры.
    """
    from ..hyphae.grow import создать_гифу, отправить_по_гифе
    from ..spores.discovery import найти_соседей

    # 1. Прямая гифа к цели
    for гифа in грибница.get('гифы', []):
        if гифа['сосед'] == кому:
            return отправить_по_гифе(гифа, почва, данные)

    # 2. Адрес известен — растим гифу напрямую
    if кому is not None:
        направление = грибница.get('исходное_направление', 'V')
        # Берём противоположное направление, чтобы дополнить
        альтернативы = {'V': 'A', 'A': 'K', 'K': 'V'}
        направление_гифы = альтернативы.get(направление, 'A')

        новая_гифа = создать_гифу(кому, направление_гифы, 1.0, почва)
        грибница.setdefault('гифы', []).append(новая_гифа)

        пакет_данных = {'кому': кому, 'данные': данные}
        return отправить_по_гифе(новая_гифа, почва, пакет_данных)

    # 3. Адрес неизвестен — ищем через споры
    соседи = найти_соседей(почва, грибница.get('исходное_направление', 'V'))
    for сосед, сигнал, сила in соседи:
        новая_гифа = создать_гифу(сосед, сигнал['направление'], сила, почва)
        грибница.setdefault('гифы', []).append(новая_гифа)
        отправить_по_гифе(новая_гифа, почва, {'кому': кому, 'данные': данные})
        return True

    return False
