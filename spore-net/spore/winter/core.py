"""Зимовка: сохранение и восстановление грибницы."""
import json
import os


def _путь_ядра(имя):
    папка = os.path.expanduser('~/.spore')
    os.makedirs(папка, exist_ok=True)
    return os.path.join(папка, f"{имя}.json")


def сохранить_ядро(грибница, имя=None):
    имя = имя or грибница.get('имя', 'безымянная')
    # Убираем префикс "пробуждена:" если он есть
    if имя.startswith('пробуждена:'):
        имя = имя.split(':', 1)[1]

    ядро = {
        'имя': имя,
        'память': грибница.get('память', [])[-100:],
        'связи': грибница.get('связи', []),
        'глубина': грибница.get('глубина', 0),
        'исходное_направление': грибница.get('исходное_направление', 'V')
    }
    путь = _путь_ядра(имя)
    with open(путь, 'w', encoding='utf-8') as f:
        json.dump(ядро, f, ensure_ascii=False, default=str)
    return ядро


def загрузить_ядро(имя):
    путь = _путь_ядра(имя)
    if not os.path.exists(путь):
        return None
    with open(путь, encoding='utf-8') as f:
        return json.load(f)


def зимовать(грибница):
    return сохранить_ядро(грибница)


def пробудиться(почва, имя):
    ядро = загрузить_ядро(имя)
    if ядро is None:
        return None

    # Свежая грибница с памятью из ядра, но БЕЗ префикса
    грибница = {
        'имя': имя,                                    # ← без префикса
        'почва': почва.тип(),
        'пористость_почвы': почва.пористость(),
        'форма': 'встраивание' if почва.пористость() > 0.5 else 'поверх',
        'споры': [],
        'гифы': [],
        'узлы': [],
        'швы': [],
        'плоды': [],
        'память': ядро['память'],
        'связи': ядро['связи'],
        'глубина': ядро['глубина'] + 1,                # ← глубина растёт
        'исходное_направление': ядро['исходное_направление'],
        'phi': {'нейтрал': 'радость', 'страх': 'интерес'},
        'выгоды': ['дать'],
        'выгоды_партнёра': ['взять'],
        'изменения': [],
        'f1': {},
        'f2': {},
        'реакции': [],
        'возмущения': []
    }
    return грибница
