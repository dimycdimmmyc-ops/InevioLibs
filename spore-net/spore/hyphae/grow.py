"""Гифы: растущие соединения между узлами."""
import json


def выбрать_форму(пористость):
    if пористость > 0.7:
        return 'встраивание'
    if пористость < 0.3:
        return 'поверх'
    return 'оба'


def создать_гифу(сосед, направление, сила, почва):
    return {
        'тип': 'гифа',
        'сосед': сосед,
        'направление': направление,
        'сила': сила,
        'почва': почва.тип(),
        'форма': выбрать_форму(почва.пористость()),
        'память': [],
        'метка': "гифа:" + str(сосед[0]) + ":" + str(сосед[1]) + ":" + направление
    }


def отправить_по_гифе(гифа, почва, данные):
    пакет = {
        'тип': 'сок',
        'гифа': гифа['метка'],
        'данные': данные,
        'память': гифа['память'][-10:]
    }
    сериализовано = json.dumps(пакет)
    print("[HYPHA] Отправляю " + str(len(сериализовано)) + " байт через гифу " + гифа['метка'])
    почва.отправить(гифа['сосед'], сериализовано.encode('utf-8'))
    гифа['сила'] = max(0.0, гифа['сила'] - 0.01)
    return True


def принять_сок(почва):
    ответ = почва.получить()
    if ответ is None:
        return None
    от_кого, данные = ответ
    print("[HYPHA] Получено от " + str(от_кого) + ": " + str(данные)[:100])
    try:
        пакет = json.loads(данные)
    except Exception as e:
        print("[HYPHA] json.loads ОШИБКА: " + str(e))
        return None
    if пакет.get('тип') == 'сок':
        print("[HYPHA] Принят сок от " + str(от_кого))
        return от_кого, пакет
    print("[HYPHA] Тип пакета не 'сок': " + str(пакет.get('тип')))
    return None